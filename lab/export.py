"""Bake the analytic scene into data files the browser can load without a server.

Outputs
-------
web/js/scene-data.js   frames (camera + primitive transforms) and material points
web/js/golden.js       reference answers for the in-browser self-check

The golden answers are computed from the **rounded** scene that is actually
shipped, so the browser check compares like with like (a mismatch here means a
real implementation divergence, not a rounding artefact).

Both files are plain ``window.X = ...`` assignments so that ``index.html`` also
works when opened directly from disk (``file://``), where ``fetch`` is blocked.
"""
from __future__ import annotations

import json
import os

import numpy as np

import geometry as G
import scene as S

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
WEB = os.path.join(ROOT, "web", "js")


def _r(x, nd=6):
    if isinstance(x, (list, tuple, np.ndarray)):
        return [_r(v, nd) for v in x]
    return round(float(x), nd)


def prim_to_json(p: dict, nd: int = 9) -> dict:
    out = {"type": p["type"], "c": _r(p["c"], nd), "R": _r(np.asarray(p["R"]).reshape(-1), nd)}
    for k in ("r", "n", "p0", "half"):
        if k in p:
            out[k] = _r(p[k], nd)
    return out


def prim_from_json(p: dict) -> dict:
    out = {"type": p["type"], "c": np.array(p["c"], float),
           "R": np.array(p["R"], float).reshape(3, 3)}
    for k in ("r", "n", "p0", "half"):
        if k in p:
            out[k] = np.array(p[k], float) if isinstance(p[k], list) else float(p[k])
    return out


def build_scene():
    """Returns (json payload, numpy frames, numpy cameras) -- all rounded."""
    frames_json, frames_np, cams = [], [], []
    for t in range(S.T):
        eye, R = S.camera_at(t)
        entry = {
            "eye": _r(eye, 9),
            "R": _r(R.reshape(-1), 9),
            "prims": [prim_to_json(p) for p in S.build_frame(t)],
        }
        frames_json.append(entry)
        # exact inverse of the JSON so the reference answers match the browser
        frames_np.append([prim_from_json(p) for p in entry["prims"]])
        cams.append((np.array(entry["eye"], float), np.array(entry["R"], float).reshape(3, 3)))

    mats = S.build_material_points()
    points = [{"p": m["prim"], "l": _r(m["local"], 4), "c": m["color"]} for m in mats]
    payload = {
        "meta": {
            "T": S.T, "W": S.W, "H": S.H,
            "fx": _r(S.INTR["fx"]), "fy": _r(S.INTR["fy"]),
            "cx": _r(S.INTR["cx"]), "cy": _r(S.INTR["cy"]),
            "fovY": S.FOV_Y, "focalNorm": _r(S.INTR["fx"] / S.W),
            "groundY": S.GROUND_Y, "orbitRadius": S.ORBIT_RADIUS,
        },
        "primNames": S.PRIM_NAMES,
        "frames": frames_json,
        "points": points,
    }
    return payload, frames_np, cams


def build_golden(frames_np, cams) -> dict:
    Q = lambda u, v, ts, tt, tc: S.query(u, v, ts, tt, tc, frames_np, cams)

    cases = []
    for (u, v, ts, tt, tc) in [
        (0.50, 0.62, 0, 3, 0), (0.31, 0.55, 0, 0, 0), (0.68, 0.58, 1, 5, 2),
        (0.22, 0.71, 2, 2, 2), (0.77, 0.66, 3, 0, 6), (0.45, 0.52, 4, 7, 4),
        (0.58, 0.75, 5, 1, 0), (0.36, 0.60, 6, 6, 6), (0.63, 0.49, 7, 2, 3),
        (0.50, 0.80, 0, 6, 1), (0.28, 0.64, 3, 3, 5), (0.72, 0.70, 1, 1, 7),
    ]:
        q = Q(u, v, ts, tt, tc)
        if q is None:
            continue
        cases.append({"q": [u, v, ts, tt, tc], "P": _r(q["P"], 8), "prim": int(q["prim"])})

    # camera recovery exactly as in the paper: an h x w ensemble of source points
    h, w = 7, 9
    grid = [(float((x + 0.5) / w), float((y + 0.5) / h)) for y in range(h) for x in range(w)]
    i_ref, j_ref = 0, 4
    A, B = [], []
    for (u, v) in grid:
        qi = Q(u, v, i_ref, i_ref, i_ref)
        qj = Q(u, v, i_ref, i_ref, j_ref)
        if qi is None or qj is None:
            continue
        A.append(qi["P"])
        B.append(qj["P"])
    R_ij, t_ij, _ = G.umeyama(np.array(B), np.array(A))

    focals = []
    for u in np.linspace(0.15, 0.85, 9):
        q = Q(float(u), 0.5, 0, 0, 0)
        if q is None:
            continue
        f = G.focal_from_point(float(u), q["P"])
        if np.isfinite(f):
            focals.append(f)

    return {
        "cases": cases,
        "pose": {"i": i_ref, "j": j_ref, "R": _r(R_ij.reshape(-1), 10), "t": _r(t_ij, 10),
                 "n": len(A)},
        "intrinsics": {"medianFocalNorm": _r(float(np.median(focals)), 10), "n": len(focals)},
    }


def write_js(path: str, var: str, payload: dict, banner: str) -> None:
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"/* {banner} -- generated by lab/export.py, do not edit by hand */\n")
        f.write(f"window.{var} = {body};\n")
    print(f"wrote {path}  ({os.path.getsize(path)/1024:.0f} KB)")


if __name__ == "__main__":
    os.makedirs(WEB, exist_ok=True)
    scene_payload, frames_np, cams = build_scene()
    write_js(os.path.join(WEB, "scene-data.js"), "SCENE_DATA", scene_payload,
             "Analytic 4D scene (exact ground truth)")
    write_js(os.path.join(WEB, "golden.js"), "GOLDEN", build_golden(frames_np, cams),
             "Reference answers for the browser self-check")
